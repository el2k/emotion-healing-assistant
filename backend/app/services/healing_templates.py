# 危机干预：出现高风险词时的严肃但有温度回应
CRISIS_REPLY = (
    "我很认真地听你说这些话，也觉得你此刻一定非常痛苦。请先记得：无论现在多难熬，"
    "这份难受是暂时的，并不代表你的未来没有希望。请你不要伤害自己，先做个深呼吸，"
    "给自己几分钟。我建议你立刻联系身边信任的人，或拨打心理援助热线（全国24小时："
    "12356；北京：010-82951332），专业人员能更好地陪着你。我会一直在这里等你，"
    "把你的感受告诉我，我们一起想办法。"
)


def get_reply(emotion_result: dict) -> str:
    """根据情绪画像选回复模板。"""
    if emotion_result.get("high_risk"):
        return CRISIS_REPLY

    cat = emotion_result["emotion_type"]
    polarity = emotion_result["polarity"]
    heal = emotion_result.get("heal_score", 0.0)

    if polarity == "positive":
        pool = POSITIVE_REPLIES.get(cat) or NEUTRAL_REPLIES
    elif polarity == "neutral":
        pool = NEUTRAL_REPLIES
    else:
        level_pool = NEGATIVE_REPLIES.get(cat)
        if isinstance(level_pool, dict):
            # 按安抚强度选层
            lvl = 3 if heal >= 0.7 else (2 if heal >= 0.45 else 1)
            pool = level_pool.get(lvl, list(level_pool.values())[0])
        elif level_pool:
            pool = level_pool
        else:
            pool = NEUTRAL_REPLIES
    return random.choice(pool)